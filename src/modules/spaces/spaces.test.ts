import { beforeEach, describe, expect, it } from "vitest";
import { useAppStore, undo } from "@/stores/app-store";
import { useWorkspaceStore } from "@/stores/workspace-store";
import { useBlinkoStore } from "@/stores/blinko-store";
import { initializeSpaces, createSpace, switchSpace, stopSpaces } from "./spaces";
import { createBackup, restoreBackup } from "@/modules/backup/backup";
import { beginSpaceOperation } from "./operations";

beforeEach(() => stopSpaces());
describe("isolated local spaces", () => {
  it("migrates legacy data once and isolates all studios, undo and persisted reload", async () => {
    const initial = useAppStore.getState().workspaceId;
    useBlinkoStore.getState().createNote({ type: "memo", content: "Private A" });
    useWorkspaceStore.getState().saveDrawing("{\"elements\":[]}");
    useAppStore.getState().addDocument({ name: "A.txt", category: "Other", size: 1 });
    await initializeSpaces();
    const second = await createSpace("Independent B");
    expect(second).toBeTruthy();
    expect(useBlinkoStore.getState().notes).toEqual([]);
    expect(useWorkspaceStore.getState().drawing).toBeUndefined();
    expect(useAppStore.getState().documents).toEqual([]);
    expect(undo()).toBeNull();
    useBlinkoStore.getState().createNote({ type: "memo", content: "Private B" });
    await switchSpace(initial);
    expect(useBlinkoStore.getState().notes.map((n) => n.content)).toContain("Private A");
    expect(useBlinkoStore.getState().notes.map((n) => n.content)).not.toContain("Private B");
    expect(useAppStore.getState().documents.some((d) => d.name === "A.txt")).toBe(true);
    await switchSpace(second!);
    stopSpaces();
    await initializeSpaces();
    expect(useBlinkoStore.getState().notes.map((n) => n.content)).toEqual(["Private B"]);
    const backup = JSON.parse(JSON.stringify(createBackup()));
    expect(Object.keys(backup.spaces.spaces)).toHaveLength(2);
    useBlinkoStore.getState().emptyTrash();
    await switchSpace(initial);
    useBlinkoStore.setState({ notes: [] });
    await restoreBackup(backup);
    expect(useAppStore.getState().workspaceId).toBe(second);
    await switchSpace(initial);
    expect(useBlinkoStore.getState().notes.map((n) => n.content)).toContain("Private A");
    const finish = beginSpaceOperation();
    await expect(switchSpace(second!)).rejects.toThrow(/cours/); finish();
    expect(useAppStore.getState().workspaceId).toBe(initial);
    useAppStore.getState().startTimer("A", "Running");
    await expect(switchSpace(second!)).rejects.toThrow(/chronomètre/);
    useAppStore.getState().stopTimer();
    stopSpaces();
  });
});
