import { test, expect } from "@playwright/test";
import { createSeed, STATE_VERSION } from "../src/lib/seed";
test("workspace migration, switching, undo and reload isolate the real modules", async ({ page }) => {
  const seed = createSeed(); seed.settings.hasCompletedOnboarding = true;
  await page.addInitScript(({ seed, version }) => localStorage.setItem("calendar-app:state", JSON.stringify({ state: seed, version })), { seed, version: STATE_VERSION });
  await page.goto("/notes");
  await page.getByPlaceholder(/idée|pensée|mind|thought|note/i).last().fill("Note privée espace A");
  await page.getByRole("button", { name: /Enregistrer|Save Note/ }).click();
  await expect(page.getByText("Note privée espace A", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Changer d'espace" }).click();
  await page.getByRole("menuitem", { name: "Créer un espace" }).click();
  await page.getByLabel(/^(Nom|Name)$/).fill("Espace B");
  await page.getByRole("button", { name: "Créer", exact: true }).click();
  await expect(page.getByText("Espace B", { exact: true })).toBeVisible();
  await expect(page.getByText("Note privée espace A", { exact: true })).toHaveCount(0);
  await page.keyboard.press("Control+z");
  await expect(page.getByText("Note privée espace A", { exact: true })).toHaveCount(0);
  await page.getByPlaceholder(/idée|pensée|mind|thought|note/i).last().fill("Note privée espace B");
  await page.getByRole("button", { name: /Enregistrer|Save Note/ }).click();
  await page.reload();
  await expect(page.getByText("Note privée espace B", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Changer d'espace" }).click();
  await page.getByRole("menuitem", { name: /Personal Workspace/ }).click();
  await expect(page.getByText("Note privée espace A", { exact: true })).toBeVisible();
  await expect(page.getByText("Note privée espace B", { exact: true })).toHaveCount(0);
  await page.goto("/presentations");
  await page.getByRole("button", { name: /Diapositive vierge/ }).click();
  await page.getByLabel("Titre de la présentation").fill("Deck espace A");
  await page.getByRole("button", { name: "Changer d'espace" }).click();
  await page.getByRole("menuitem", { name: /Espace B/ }).click();
  await expect(page.getByRole("button", { name: /Diapositive vierge/ })).toBeVisible();
  await expect(page.getByLabel("Titre de la présentation")).toHaveCount(0);
});
